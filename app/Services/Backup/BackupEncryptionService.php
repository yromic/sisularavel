<?php

namespace App\Services\Backup;

use Illuminate\Support\Facades\File;
use RuntimeException;

class BackupEncryptionService
{
    public const CIPHER = 'aes-256-gcm';

    public const MAGIC_HEADER = "SISURAT_GCM1\0"; // 13 bytes header identifier

    public const IV_LENGTH = 12; // 96-bit standard nonce for GCM

    public const TAG_LENGTH = 16; // 128-bit authentication tag

    /**
     * Encrypt an archive file using AES-256-GCM authenticated cipher.
     *
     * @return array Encryption metadata including output path and SHA-256 of encrypted file
     */
    public function encryptArchive(string $sourcePath, string $encryptedPath, ?string $passphrase = null): array
    {
        if (! File::exists($sourcePath)) {
            throw new RuntimeException("Source archive to encrypt does not exist: {$sourcePath}");
        }

        $binaryKey = $this->deriveBinaryKey($passphrase);
        $iv = random_bytes(self::IV_LENGTH);
        $tag = '';

        $plaintext = File::get($sourcePath);

        // Associated Authenticated Data (AAD) binds backup metadata to encryption
        $aad = self::MAGIC_HEADER;

        $ciphertext = openssl_encrypt(
            $plaintext,
            self::CIPHER,
            $binaryKey,
            OPENSSL_RAW_DATA,
            $iv,
            $tag,
            $aad,
            self::TAG_LENGTH
        );

        if ($ciphertext === false) {
            throw new RuntimeException('Authenticated encryption failed: OpenSSL returned false.');
        }

        // Pack: Magic Header (13B) + IV (12B) + Tag (16B) + Ciphertext
        $payload = self::MAGIC_HEADER.$iv.$tag.$ciphertext;

        // Ensure target directory exists
        $dir = dirname($encryptedPath);
        if (! File::isDirectory($dir)) {
            File::makeDirectory($dir, 0755, true, true);
        }

        File::put($encryptedPath, $payload);

        // Wipe plain memory
        unset($plaintext, $ciphertext, $payload);

        return [
            'encrypted_path' => $encryptedPath,
            'cipher' => self::CIPHER,
            'sha256' => hash_file('sha256', $encryptedPath),
            'size_bytes' => File::size($encryptedPath),
        ];
    }

    /**
     * Decrypt an archive file previously encrypted with AES-256-GCM.
     *
     * @throws RuntimeException on tampering, header mismatch, or incorrect decryption key.
     */
    public function decryptArchive(string $encryptedPath, string $decryptedPath, ?string $passphrase = null): bool
    {
        if (! File::exists($encryptedPath)) {
            throw new RuntimeException("Encrypted archive does not exist: {$encryptedPath}");
        }

        $binaryKey = $this->deriveBinaryKey($passphrase);
        $content = File::get($encryptedPath);

        $headerLen = strlen(self::MAGIC_HEADER);
        $minLen = $headerLen + self::IV_LENGTH + self::TAG_LENGTH;

        if (strlen($content) < $minLen) {
            throw new RuntimeException('Invalid encrypted archive: File size is smaller than AEAD header and tag.');
        }

        // 1. Verify Magic Header
        $magic = substr($content, 0, $headerLen);
        if (! hash_equals(self::MAGIC_HEADER, $magic)) {
            throw new RuntimeException('Invalid archive header: File was not generated by SISURAT Backup Encryption Engine.');
        }

        // 2. Extract IV & Tag
        $iv = substr($content, $headerLen, self::IV_LENGTH);
        $tag = substr($content, $headerLen + self::IV_LENGTH, self::TAG_LENGTH);
        $ciphertext = substr($content, $headerLen + self::IV_LENGTH + self::TAG_LENGTH);

        $aad = self::MAGIC_HEADER;

        // 3. Authenticated Decryption
        $decrypted = openssl_decrypt(
            $ciphertext,
            self::CIPHER,
            $binaryKey,
            OPENSSL_RAW_DATA,
            $iv,
            $tag,
            $aad
        );

        if ($decrypted === false) {
            // This happens when either the key is wrong OR ciphertext/tag was tampered by even 1 byte
            throw new RuntimeException('Tamper detected or invalid key: Authenticated tag verification failed during decryption.');
        }

        $targetDir = dirname($decryptedPath);
        if (! File::isDirectory($targetDir)) {
            File::makeDirectory($targetDir, 0755, true, true);
        }

        File::put($decryptedPath, $decrypted);
        unset($decrypted, $content, $ciphertext);

        return true;
    }

    /**
     * Derive a deterministic 32-byte binary key from passphrase or application key.
     */
    public function deriveBinaryKey(?string $passphrase = null): string
    {
        $secret = $passphrase
            ?? config('backup.encryption.key')
            ?? config('app.key');

        if (empty($secret)) {
            throw new RuntimeException('Backup encryption key is not configured. Set BACKUP_ENCRYPTION_KEY or APP_KEY.');
        }

        // Normalize base64 Laravel app key if formatted as 'base64:...'
        if (str_starts_with($secret, 'base64:')) {
            $secret = base64_decode(substr($secret, 7));
        }

        // Derive uniform 256-bit (32 bytes) binary key using SHA-256
        return hash('sha256', $secret, true);
    }
}
